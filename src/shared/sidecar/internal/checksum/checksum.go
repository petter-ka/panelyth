// Package checksum creates and reads checksum files (Stage C08): SHA-256,
// SHA-1 and MD5 lists in the format of the sha256sum family, and CRC32 lists
// as .sfv files.
package checksum

import (
	"bufio"
	"context"
	"crypto/md5"
	"crypto/sha1"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"hash"
	"hash/crc32"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"
)

// Algo names a checksum algorithm (mirrors src/shared/contracts HashAlgorithm).
type Algo string

const (
	SHA256 Algo = "sha256"
	SHA1   Algo = "sha1"
	MD5    Algo = "md5"
	CRC32  Algo = "crc32"
)

// Valid reports whether a is a known algorithm.
func (a Algo) Valid() bool {
	return a == SHA256 || a == SHA1 || a == MD5 || a == CRC32
}

// Ext is the extension of the algorithm's checksum files, with the dot.
func (a Algo) Ext() string {
	if a == CRC32 {
		return ".sfv"
	}
	return "." + string(a)
}

func (a Algo) new() hash.Hash {
	switch a {
	case SHA1:
		return sha1.New()
	case MD5:
		return md5.New()
	case CRC32:
		return crc32.NewIEEE()
	}
	return sha256.New()
}

// hexLen is the length of a sum in hex digits.
func (a Algo) hexLen() int { return a.new().Size() * 2 }

// ByName returns the algorithm of a checksum file by its extension.
func ByName(name string) (Algo, bool) {
	switch strings.ToLower(filepath.Ext(name)) {
	case ".sha256":
		return SHA256, true
	case ".sha1":
		return SHA1, true
	case ".md5":
		return MD5, true
	case ".sfv":
		return CRC32, true
	}
	return "", false
}

// Options are the hooks of hashing one file.
type Options struct {
	// Progress receives the bytes hashed since its previous call.
	Progress func(n int64)
	// Gate is a pause point: it blocks while a job is paused.
	Gate func(ctx context.Context) error
}

// BufferSize is the read buffer (pooled, one per file being hashed).
const BufferSize = 1 << 20

var bufPool = sync.Pool{New: func() any { b := make([]byte, BufferSize); return &b }}

// File hashes a file in one streamed pass and returns the sum in lower-case
// hex (CRC32 in upper case, as .sfv files have it).
func File(ctx context.Context, path string, a Algo, o *Options) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := a.new()
	bp := bufPool.Get().(*[]byte)
	defer bufPool.Put(bp)
	buf := *bp
	for {
		if o != nil && o.Gate != nil {
			if err := o.Gate(ctx); err != nil {
				return "", err
			}
		} else if err := ctx.Err(); err != nil {
			return "", err
		}
		n, err := f.Read(buf)
		if n > 0 {
			h.Write(buf[:n])
			if o != nil && o.Progress != nil {
				o.Progress(int64(n))
			}
		}
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return "", err
		}
	}
	sum := hex.EncodeToString(h.Sum(nil))
	if a == CRC32 {
		sum = strings.ToUpper(sum)
	}
	return sum, nil
}

// Header is the first line of a new .sfv file (a comment); other formats
// have none.
func Header(a Algo) string {
	if a == CRC32 {
		return "; Generated by Panelyth\n"
	}
	return ""
}

// Line formats one entry: "sum *path" (binary mode) for the sha256sum
// family, "path SUM" for .sfv. rel uses forward slashes.
func Line(a Algo, sum, rel string) string {
	if a == CRC32 {
		return rel + " " + sum + "\n"
	}
	if strings.ContainsAny(rel, "\\\n") {
		// The family's escaping: a leading backslash marks an escaped name.
		rel = strings.NewReplacer(`\`, `\\`, "\n", `\n`).Replace(rel)
		return `\` + sum + " *" + rel + "\n"
	}
	return sum + " *" + rel + "\n"
}

// Entry is one line of a checksum file.
type Entry struct {
	// Path is relative to the checksum file's folder, with forward slashes.
	Path string
	// Sum is in lower-case hex.
	Sum string
}

// Limits of a checksum file being read.
const (
	MaxEntries   = 1_000_000
	maxLineBytes = 64 << 10
)

// utf8Mark is the byte order mark some editors put first.
var utf8Mark = string([]byte{0xEF, 0xBB, 0xBF})

// ErrFormat is returned for files that are not checksum lists.
var ErrFormat = errors.New("not a checksum file")

func isHex(s string) bool {
	for _, c := range s {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F') {
			return false
		}
	}
	return s != ""
}

// Parse reads a checksum file: "sum  path" and "sum *path" lines (also with
// escaped names), the BSD form "SHA256 (path) = sum", and "path SUM" for
// .sfv. Empty lines and comments (";" and "#") are skipped, a UTF-8 mark and
// CR LF line ends are accepted. A line it cannot read fails the whole file,
// so a damaged list is never taken for a shorter one.
func Parse(r io.Reader, a Algo) ([]Entry, error) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64<<10), maxLineBytes)
	var out []Entry
	want := a.hexLen()
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimRight(sc.Text(), "\r")
		if n == 1 {
			line = strings.TrimPrefix(line, utf8Mark)
		}
		if strings.TrimSpace(line) == "" || line[0] == ';' || line[0] == '#' {
			continue
		}
		var e Entry
		switch {
		case a == CRC32:
			i := strings.LastIndexByte(line, ' ')
			if i <= 0 {
				return nil, fmt.Errorf("%w: line %d", ErrFormat, n)
			}
			e = Entry{Path: strings.TrimRight(line[:i], " "), Sum: line[i+1:]}
		case strings.Contains(line, ") = "):
			// BSD: "SHA256 (name) = sum".
			open, eq := strings.Index(line, " ("), strings.LastIndex(line, ") = ")
			if open < 0 || eq < open {
				return nil, fmt.Errorf("%w: line %d", ErrFormat, n)
			}
			e = Entry{Path: line[open+2 : eq], Sum: line[eq+4:]}
		default:
			escaped := strings.HasPrefix(line, `\`)
			if escaped {
				line = line[1:]
			}
			if len(line) < want+2 || line[want] != ' ' || (line[want+1] != ' ' && line[want+1] != '*') {
				return nil, fmt.Errorf("%w: line %d", ErrFormat, n)
			}
			e = Entry{Path: line[want+2:], Sum: line[:want]}
			if escaped {
				e.Path = strings.NewReplacer(`\\`, `\`, `\n`, "\n").Replace(e.Path)
			}
		}
		if len(e.Sum) != want || !isHex(e.Sum) || e.Path == "" {
			return nil, fmt.Errorf("%w: line %d", ErrFormat, n)
		}
		e.Sum = strings.ToLower(e.Sum)
		e.Path = strings.ReplaceAll(e.Path, `\`, "/")
		out = append(out, e)
		if len(out) > MaxEntries {
			return nil, fmt.Errorf("%w: more than %d entries", ErrFormat, MaxEntries)
		}
	}
	if err := sc.Err(); err != nil {
		if errors.Is(err, bufio.ErrTooLong) {
			return nil, fmt.Errorf("%w: a line is too long", ErrFormat)
		}
		return nil, err
	}
	return out, nil
}

// Resolve returns the file an entry names inside dir. Entries that are
// absolute or leave the folder are refused (ok is false): a checksum file
// only ever speaks for the files beside and below it.
func Resolve(dir, rel string) (string, bool) {
	p := filepath.FromSlash(rel)
	if rel == "" || filepath.IsAbs(p) || filepath.VolumeName(p) != "" || strings.HasPrefix(rel, "/") || !filepath.IsLocal(p) {
		return "", false
	}
	return filepath.Join(dir, p), true
}
