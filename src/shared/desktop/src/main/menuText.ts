/** By the language codes of Settings → Appearance (`@panelyth/i18n` LOCALES). */
export const MENU_TEXT: Readonly<Record<string, MenuText>> = { en, hu, es, it, fr, pl, ru, de }

/** English for a language the menu has no text for. */
export const menuText = (language: string | undefined): MenuText =>
  (language !== undefined && Object.hasOwn(MENU_TEXT, language) && MENU_TEXT[language]) || en
